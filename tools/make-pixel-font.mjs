// bitmap -> merged rectangles [x, y, w, h] in art pixels (y up from the baseline)
function rects(rows, bold) {
  const w = Math.max(...rows.map((r) => r.length)) + (bold ? 1 : 0);
  const on = rows.map((r) => Array.from({ length: w }, (_, x) => r[x] === '#' || (bold && r[x - 1] === '#')));
  const out = [];
  const used = on.map((r) => r.map(() => false));
  for (let y = 0; y < on.length; y++) for (let x = 0; x < w; x++) {
    if (!on[y][x] || used[y][x]) continue;
    let x2 = x; while (x2 + 1 < w && on[y][x2 + 1] && !used[y][x2 + 1]) x2++;
    let y2 = y;
    for (;;) {
      if (y2 + 1 >= on.length) break;
      let ok = true;
      for (let k = x; k <= x2; k++) if (!on[y2 + 1][k] || used[y2 + 1][k]) ok = false;
      if (!ok) break;
      y2++;
    }
    for (let j = y; j <= y2; j++) for (let k = x; k <= x2; k++) used[j][k] = true;
    out.push([x, 7 - y2 - 1, x2 - x + 1, y2 - y + 1]);
  }
  return { out, w };
}

const b16 = (n) => [(n >> 8) & 255, n & 255];
const b32 = (n) => [(n >>> 24) & 255, (n >>> 16) & 255, (n >>> 8) & 255, n & 255];
const pad4 = (a) => { while (a.length % 4) a.push(0); return a; };

function build(bold) {
  const chars = Object.keys(G).sort((a, b) => a.codePointAt(0) - b.codePointAt(0));
  const glyphs = [{ r: [[0, 0, 4, 7]], w: 4 }]; // .notdef
  chars.forEach((c) => {
    const { out, w } = rects((bold && BOLD[c] || G[c]).split('/'), bold && !BOLD[c] && !/\s/.test(c));
    glyphs.push({ r: out, w });
  });
  let glyf = [], loca = [0], maxPts = 0, maxCon = 0, xMaxAll = 0;
  const hmtx = [];
  glyphs.forEach((g) => {
    const adv = (g.w + 1) * U;
    hmtx.push(...b16(adv), ...b16(g.r.length ? Math.min(...g.r.map((q) => q[0])) * U : 0));
    if (g.r.length) {
      const xs = g.r.flatMap((q) => [q[0], q[0] + q[2]]), ys = g.r.flatMap((q) => [q[1], q[1] + q[3]]);
      const bb = [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)].map((v) => v * U);
      xMaxAll = Math.max(xMaxAll, bb[2]);
      const d = [...b16(g.r.length), ...bb.flatMap(b16)];
      g.r.forEach((_, i) => d.push(...b16(i * 4 + 3)));
      d.push(0, 0); // no instructions
      const pts = g.r.flatMap(([x, y, w, h]) => [[x, y], [x, y + h], [x + w, y + h], [x + w, y]].map((p) => [p[0] * U, p[1] * U]));
      pts.forEach(() => d.push(1));
      let px = 0, py = 0;
      pts.forEach((p) => { d.push(...b16(p[0] - px)); px = p[0]; });
      pts.forEach((p) => { d.push(...b16(p[1] - py)); py = p[1]; });
      glyf.push(...pad4(d));
      maxPts = Math.max(maxPts, pts.length); maxCon = Math.max(maxCon, g.r.length);
    }
    loca.push(glyf.length);
  });
  // cmap format 4
  const segs = [];
  chars.forEach((c, i) => {
    const cp = c.codePointAt(0), last = segs[segs.length - 1];
    if (last && last.end + 1 === cp) last.end = cp; else segs.push({ start: cp, end: cp, gid: i + 1 });
  });
  segs.push({ start: 0xffff, end: 0xffff, gid: 0 });
  const n = segs.length, pow = Math.floor(Math.log2(n)), sr = 2 * 2 ** pow;
  const sub = [...b16(4), ...b16(16 + n * 8), ...b16(0), ...b16(n * 2), ...b16(sr), ...b16(pow), ...b16(n * 2 - sr),
    ...segs.flatMap((s) => b16(s.end)), 0, 0, ...segs.flatMap((s) => b16(s.start)),
    ...segs.flatMap((s) => b16((s.end === 0xffff ? 1 : s.gid - s.start) & 0xffff)), ...segs.flatMap(() => [0, 0])];
  const cmap = [...b16(0), ...b16(1), ...b16(3), ...b16(1), ...b32(12), ...sub];
  const weight = bold ? 700 : 400;
  const names = { 1: 'Homestead Pixel', 2: bold ? 'Bold' : 'Regular', 4: 'Homestead Pixel' + (bold ? ' Bold' : ''), 6: 'HomesteadPixel-' + (bold ? 'Bold' : 'Regular') };
  let str = [], recs = [];
  Object.entries(names).forEach(([id, s]) => {
    const b = [...s].flatMap((c) => b16(c.charCodeAt(0)));
    recs.push(...b16(3), ...b16(1), ...b16(0x409), ...b16(+id), ...b16(b.length), ...b16(str.length));
    str.push(...b);
  });
  const name = [...b16(0), ...b16(4), ...b16(6 + 48), ...recs, ...str];
  const tables = {
    'OS/2': [...b16(4), ...b16(500), ...b16(weight), ...b16(5), ...b16(0), ...b16(600), ...b16(600), ...b16(0), ...b16(100), ...b16(600), ...b16(600), ...b16(0), ...b16(400), ...b16(100), ...b16(300), ...b16(0),
      ...Array(10).fill(0), ...b32(1), ...b32(0), ...b32(0), ...b32(0), 72, 79, 77, 69, ...b16(bold ? 0x20 : 0x40), ...b16(32), ...b16(0x2026), ...b16(ASC), ...b16(-DESC), ...b16(100), ...b16(ASC), ...b16(DESC),
      ...b32(1), ...b32(0), ...b16(500), ...b16(700), ...b16(0), ...b16(32), ...b16(1)],
    cmap, glyf,
    head: [...b32(0x10000), ...b32(0x10000), ...b32(0), ...b32(0x5f0f3cf5), ...b16(0x000b), ...b16(EM), ...Array(16).fill(0), ...b16(0), ...b16(-DESC), ...b16(xMaxAll), ...b16(700), ...b16(bold ? 1 : 0), ...b16(8), ...b16(2), ...b16(1), ...b16(0)],
    hhea: [...b32(0x10000), ...b16(ASC), ...b16(-DESC), ...b16(100), ...b16(800), ...b16(0), ...b16(0), ...b16(xMaxAll), ...b16(1), ...b16(0), ...b16(0), ...Array(8).fill(0), ...b16(0), ...b16(glyphs.length)],
    hmtx,
    loca: loca.flatMap(b32),
    maxp: [...b32(0x10000), ...b16(glyphs.length), ...b16(maxPts), ...b16(maxCon), ...b16(0), ...b16(0), ...b16(2), ...b16(0), ...b16(0), ...b16(0), ...b16(0), ...b16(0), ...b16(0), ...b16(0), ...b16(0)],
    name,
    post: [...b32(0x30000), ...b32(0), ...b16(-100), ...b16(100), ...b32(0), ...b32(0), ...b32(0), ...b32(0), ...b32(0)],
  };
  const tags = Object.keys(tables).sort();
  const nt = tags.length, p2 = Math.floor(Math.log2(nt)), sr2 = 16 * 2 ** p2;
  let off = 12 + nt * 16, dir = [], body = [];
  const sum = (a) => { let s = 0; for (let i = 0; i < a.length; i += 4) s = (s + (((a[i] << 24) | (a[i + 1] << 16) | (a[i + 2] << 8) | a[i + 3]) >>> 0)) >>> 0; return s; };
  let headAt = 0;
  tags.forEach((t) => {
    const len = tables[t].length, data = pad4(tables[t].slice());
    if (t === 'head') headAt = off;
    dir.push(...[...t].map((c) => c.charCodeAt(0)), ...b32(sum(data)), ...b32(off), ...b32(len));
    body.push(...data); off += data.length;
  });
  const file = [...b32(0x10000), ...b16(nt), ...b16(sr2), ...b16(p2), ...b16(nt * 16 - sr2), ...dir, ...body];
  const adj = (0xb1b0afba - sum(file)) >>> 0;
  b32(adj).forEach((v, i) => { file[headAt + 8 + i] = v; });
  return Buffer.from(file);
}

const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'vendor', 'fonts');
for (const bold of [false, true]) {
  const f = path.join(out, `homestead-pixel-${bold ? 700 : 400}.ttf`);
  fs.writeFileSync(f, build(bold));
  console.log(path.basename(f), fs.statSync(f).size, 'bytes,', Object.keys(G).length, 'glyphs');
}
